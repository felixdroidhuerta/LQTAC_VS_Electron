const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('voiceStudio', Object.freeze({
  getInfo: () => ipcRenderer.invoke('app:info'),
  exportProject: data => ipcRenderer.invoke('project:export', data),
  exportAudio: data => ipcRenderer.invoke('audio:export', data),
  convertBatch: data => ipcRenderer.invoke('audio:batch', data),
  onBatchProgress: callback => { const listener = (_event, data) => callback(data); ipcRenderer.on('audio:batchProgress', listener); return () => ipcRenderer.removeListener('audio:batchProgress', listener); },
  exportTranscript: data => ipcRenderer.invoke('stt:export', data),
  openManual: () => ipcRenderer.invoke('help:manual'),
  openExternal: url => ipcRenderer.invoke('app:openExternal', url),
  getAzureCredentials: () => ipcRenderer.invoke('azure:environment'),
  getStatus: () => ipcRenderer.invoke('voice:status'),
  getSttStatus: () => ipcRenderer.invoke('stt:status'),
  transcribe: payload => ipcRenderer.invoke('stt:transcribe', payload),
  ping: () => ipcRenderer.invoke('voice:ping'),
  listVoices: () => ipcRenderer.invoke('voice:listVoices'),
  generateVoice: payload => ipcRenderer.invoke('voice:generate', payload),
  generateEdge: payload => ipcRenderer.invoke('voice:generateEdge', payload),
  listCloneProfiles: () => ipcRenderer.invoke('clone:listProfiles'),
  saveCloneProfile: payload => ipcRenderer.invoke('clone:saveProfile', payload),
  generateClone: payload => ipcRenderer.invoke('clone:generate', payload),
  analyzeAudio: inputPath => ipcRenderer.invoke('audio:analyze', { input_path: inputPath }),
  renderAudio: payload => ipcRenderer.invoke('audio:render', payload),
  mergeAudio: payload => ipcRenderer.invoke('audio:merge', payload),
  convertAudio: payload => ipcRenderer.invoke('audio:convert', payload),
  writeIdTags: payload => ipcRenderer.invoke('audio:idtag', payload),
  splitAudio: payload => ipcRenderer.invoke('audio:split', payload),
  selectAudioFiles: options => ipcRenderer.invoke('audio:selectFiles', options),
  selectAudioFile: options => ipcRenderer.invoke('audio:selectFile', options),
  selectImageFile: options => ipcRenderer.invoke('audio:selectImageFile', options),
  selectSttModel: options => ipcRenderer.invoke('stt:selectModel', options),
  selectSttRuntime: options => ipcRenderer.invoke('stt:selectRuntime', options),
  newProject: () => ipcRenderer.invoke('project:reset'),
  saveProject: data => ipcRenderer.invoke('project:save', data),
  listProjects: () => ipcRenderer.invoke('project:list'),
  openProject: filePath => ipcRenderer.invoke('project:open', filePath),
  deleteProject: filePath => ipcRenderer.invoke('project:delete', filePath),
  getProjectAudioInfo: relativePath => ipcRenderer.invoke('project:audioInfo', relativePath),
  revealOutput: filePath => ipcRenderer.invoke('voice:revealOutput', filePath)
}));
